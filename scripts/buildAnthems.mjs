// Turns data/anthems/*.json (from the anthem-scores dataset, https://github.com/MarianBecher/anthem-scores)
// into src/audio/anthemData.generated.ts. Run: node scripts/buildAnthems.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

/** ISO 3166 alpha-2 (dataset) to the three letter nationality code the game uses, with the usual alternative spellings. */
const GAME = {
  GB: ["GBR", "ENG", "SCO", "WAL"], FR: ["FRA"], IT: ["ITA"], DE: ["GER", "DEU"], ES: ["ESP"], MX: ["MEX"], JP: ["JPN"], US: ["USA"], CA: ["CAN"], AU: ["AUS"],
  CN: ["CHN"], NL: ["NED", "NLD"], FI: ["FIN"], DK: ["DEN", "DNK"], CH: ["SUI", "CHE"], AT: ["AUT"], BE: ["BEL"], PL: ["POL"], SE: ["SWE"], IN: ["IND"], ID: ["INA", "IDN"],
  RU: ["RUS"], CZ: ["CZE"], HU: ["HUN"], HR: ["CRO", "HRV"], GR: ["GRE", "GRC"], IL: ["ISR"], PK: ["PAK"], UA: ["UKR"], SK: ["SVK"], AL: ["ALB"], SM: ["SMR"],
  AD: ["AND"], VA: ["VAT"], IM: ["IMN"], ZA: ["RSA", "ZAF"],
};
const dir = new URL("../data/anthems/", import.meta.url);
const out = {};
const credits = {};
for (const f of readdirSync(dir).filter((x) => /^[A-Z]{2}\.json$/.test(x))) {
  const d = JSON.parse(readFileSync(new URL(f, dir), "utf8"));
  const codes = GAME[d.code];
  if (!codes) { console.warn("no game code for", d.code); continue; }
  const r = (x) => Math.round(x * 1000) / 1000;
  const rec = {
    title: d.title, composer: d.composer, bpm: d.bpm, bar: d.beatsPerBar, tonic: d.key?.tonic ?? 0, len: r(d.lengthBeats),
    mel: d.melody.map(([a, m, l]) => [r(a), m, r(l)]),
    bass: (d.bass ?? []).map(([a, m, l]) => [r(a), m, r(l)]),
    inner: (d.inner ?? []).map((n) => (Array.isArray(n) ? n : [n.at ?? n[0], n.midi ?? n[1], n.len ?? n[2]])),
  };
  out[d.code] = rec;
  credits[d.code] = `${d.title} (${d.composer}) - ${d.author}, ${d.license}, ${d.source}`;
  rec.codes = codes;
}
const body = `// GENERATED by scripts/buildAnthems.mjs from data/anthems. Do not edit by hand.
// Melodies are converted from freely licensed scores; see data/anthems/CREDITS.md for each source and licence.
export interface AnthemRecord { title: string; composer: string; bpm: number; bar: number; tonic: number; len: number; mel: number[][]; bass: number[][]; inner: unknown[]; codes: string[] }
export const ANTHEM_RECORDS: Record<string, AnthemRecord> = ${JSON.stringify(out)};
export const ANTHEM_CREDITS: Record<string, string> = ${JSON.stringify(credits, null, 1)};
`;
writeFileSync(new URL("../src/audio/anthemData.generated.ts", import.meta.url), body);
console.log("wrote", Object.keys(out).length, "anthems");
