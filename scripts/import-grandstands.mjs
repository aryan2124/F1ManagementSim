#!/usr/bin/env node
/**
 * OPTIONAL. Pulls real grandstand outlines from OpenStreetMap (Overpass API, ODbL) and writes
 * src/game/venueGeo.generated.ts, in the same metre frame as circuitGeo.generated.ts.
 *
 * Usage: node scripts/import-grandstands.mjs /path/to/f1-circuits-repo [circuit-id ...]
 *
 * It needs internet access to overpass-api.de. The game works without it (it falls back to the
 * approximate anchors in src/game/venues.ts). OpenStreetMap data (c) OpenStreetMap contributors, ODbL.
 *
 * NOTE: this script was written without being able to reach Overpass from my sandbox, so it has not
 * been run against live data. If a circuit returns nothing it is simply left out.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SRC = process.argv[2];
if (!SRC) {
  console.error("usage: node scripts/import-grandstands.mjs <path to f1-circuits repo> [circuit-id ...]");
  process.exit(1);
}
const only = process.argv.slice(3);
const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), "../src/game/venueGeo.generated.ts");
const ENDPOINT = "https://overpass-api.de/api/interpreter";
const PAD = 0.004; // degrees around the circuit

const files = fs.readdirSync(path.join(SRC, "circuits")).filter((f) => f.endsWith(".geojson")).sort();
const result = {};

function rawLen(p) {
  let l = 0;
  for (let i = 0; i < p.length; i++) l += Math.hypot(p[(i + 1) % p.length].x - p[i].x, p[(i + 1) % p.length].y - p[i].y);
  return l;
}

for (const f of files) {
  const id = f.replace(".geojson", "");
  if (only.length && !only.includes(id)) continue;
  const feat = JSON.parse(fs.readFileSync(path.join(SRC, "circuits", f), "utf8")).features[0];
  let coords = feat.geometry.coordinates;
  const lons = coords.map((c) => c[0]);
  const lats = coords.map((c) => c[1]);
  const lat0 = lats.reduce((a, b) => a + b, 0) / lats.length;
  const lon0 = lons.reduce((a, b) => a + b, 0) / lons.length;
  const kx = 111320 * Math.cos((lat0 * Math.PI) / 180);
  const proj = (lon, lat) => ({ x: (lon - lon0) * kx, y: -(lat - lat0) * 110574 });
  const raw = coords.map((c) => proj(c[0], c[1]));
  const k = feat.properties.length / rawLen(raw);
  const bbox = [Math.min(...lats) - PAD, Math.min(...lons) - PAD, Math.max(...lats) + PAD, Math.max(...lons) + PAD].join(",");
  const q = `[out:json][timeout:60];(way["building"="grandstand"](${bbox});way["leisure"="stadium"](${bbox});way["amenity"="grandstand"](${bbox});way["building"="stadium"](${bbox}););out center tags;`;
  try {
    const res = await fetch(ENDPOINT, { method: "POST", body: "data=" + encodeURIComponent(q), headers: { "content-type": "application/x-www-form-urlencoded" } });
    if (!res.ok) throw new Error("HTTP " + res.status);
    const js = await res.json();
    const out = [];
    for (const el of js.elements ?? []) {
      if (!el.center) continue;
      const p = proj(el.center.lon, el.center.lat);
      out.push({ name: (el.tags?.name ?? "").toUpperCase().slice(0, 22), x: Math.round(p.x * k * 10) / 10, y: Math.round(p.y * k * 10) / 10 });
    }
    if (out.length) result[id] = out;
    console.log(id, out.length, "stands");
  } catch (e) {
    console.warn(id, "failed:", String(e));
  }
  await new Promise((r) => setTimeout(r, 1500)); // be polite to the public Overpass server
}

const header = `// GENERATED by scripts/import-grandstands.mjs from OpenStreetMap (ODbL). Do not edit by hand.\n// Same metre frame as circuitGeo.generated.ts, but only approximately centred (the importer uses the raw centroid).\n`;
const body = `export interface SurveyedStand {\n  name: string;\n  x: number;\n  y: number;\n}\n\nexport const VENUE_GEO: Record<string, SurveyedStand[]> = ${JSON.stringify(result)};\n`;
fs.writeFileSync(OUT, header + body);
console.log("wrote", OUT);
